/*
 * address: bpc pcu ppu c908 base address
 * core:  0~7, 0~3:c908, 4~7:c920
 */
#define CPU_SS_CORE_ADDR(address, core) (address + (core >> 2) * 0x4000 - (core % 4) * 0x200)
#define AP_CORE_BPC_ADDR(core, offset) (CPU_SS_CORE_ADDR(0x10100c00, core) + offset)
#define AP_CORE_PCU_ADDR(core, offset) (CPU_SS_CORE_ADDR(0x10101600, core) + offset)
#define AP_CORE_PPU_ADDR(core, offset) (CPU_SS_CORE_ADDR(0x10102000, core) + offset)

